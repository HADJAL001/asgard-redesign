import db from "../lib/db"

/* ================================================================
   OSGARD · Миграция 094: журнал участия генераций в обучении
   ----------------------------------------------------------------
   ПРОБЛЕМА, КОТОРУЮ ЗАКРЫВАЕМ. С волны 2 платформа копит уроки своих
   поломок и подмешивает их в промпт генерации, а с волны 4 показывает
   это в витрине. Но витрина отвечала только на вопрос «какие уроки
   доходят до модели» — и ни одна цифра не отвечала на главный:
   «в КАКОЙ ДОЛЕ генераций обучение вообще участвует».

   Аудит волны 7 показал, что доля эта была далека от единицы, причём
   молча:

     1. Шаблонный путь (`adaptTemplate`) — глубина `quick`, то есть
        путь по умолчанию и основной трафик — уроков не получал вовсе:
        промпт адаптации собирался без них.
     2. Кэш готовых результатов (`app-generator.appCacheKey`) уроки в
        ключ не включал. Попадание отдавало код, рождённый под ПРОШЛЫМ
        набором уроков, ещё сутки после того, как набор изменился.

   Ни то, ни другое нельзя было заметить: обучение не оставляло следа
   в БД, и «платформа умнеет с каждой генерации» оставалось верой.
   Поэтому первым делом — не исправление, а ИЗМЕРЕНИЕ: таблица, по
   которой доля считается фактом, а не рассуждением, и считается
   одинаково до и после правки.

   ЧТО ДЕЛАЕМ. Одна изолированная таблица, одна строка на генерацию:

     project_id      INTEGER PK — генерация привязана к проекту 1:1
                                  (повторная доработка перезаписывает
                                  строку: она про ПОСЛЕДНЮЮ выдачу).
     depth           TEXT       — quick/standard/deep: видно, беден ли
                                  обучением именно бесплатный путь.
     path            TEXT       — какой ветвью получен код:
                                  template-ai | template-local |
                                  ai | ai-cached | fallback.
     lessons_taught  INTEGER    — сколько уроков дошло до модели В ЭТОЙ
                                  генерации. Ноль — генерация ничему не
                                  училась, как бы богата ни была память.
     lessons_learned INTEGER    — сколько уроков генерация вернула в
                                  память (обратное направление).
     fingerprint     TEXT       — отпечаток набора уроков, под которым
                                  рождён код. Нужен ровно для кэша:
                                  попадание честно считается обучающимся
                                  только если отпечаток совпадает с
                                  текущим набором.
     created_at      INTEGER    — время выдачи (для окна «за 7 дней»).

   ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ КОЛОНКИ В `projects`. Строка нужна и
   тогда, когда проект удалён: доля обучающихся генераций — свойство
   платформы, а не пользователя. Плюс `projects` — самая горячая таблица
   схемы, и добавлять в неё колонки ради диагностики дорого.

   Ничего существующего не мутирует и не удаляет. Идемпотентно
   (`IF NOT EXISTS`), самовызов на импорте — как 092/093/097.
   ================================================================ */

export function runGenerationLearningMigration() {
  db.exec(`
    CREATE TABLE IF NOT EXISTS generation_learning (
      project_id      INTEGER PRIMARY KEY,
      depth           TEXT NOT NULL,
      path            TEXT NOT NULL,
      lessons_taught  INTEGER NOT NULL DEFAULT 0,
      lessons_learned INTEGER NOT NULL DEFAULT 0,
      fingerprint     TEXT,
      created_at      INTEGER NOT NULL
    );
  `)

  /* Витрина спрашивает «доля за последние N дней» — без индекса это полный скан
     таблицы, растущей вместе со всем трафиком генерации. */
  db.exec(`CREATE INDEX IF NOT EXISTS idx_generation_learning_created ON generation_learning(created_at)`)

  console.log("✅ Migration 094: Generation learning ledger ready (share of generations that actually learn)")
}

runGenerationLearningMigration()
