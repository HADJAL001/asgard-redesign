import db from "../lib/db"

/* ================================================================
   OSGARD · Миграция 097: урок, который не работает, обязан уступить
   ----------------------------------------------------------------
   ПРОБЛЕМА, КОТОРУЮ ЗАКРЫВАЕМ. Волна 5 научила платформу формулировать
   уроки самой и — главное — ИЗМЕРЯТЬ их пользу: `occurrences_at_authoring`
   даёт точку отсчёта, разница с текущим счётчиком показывает, сколько
   раз дефект повторился ПОСЛЕ того, как урок дошёл до модели.

   Но на это измерение никто не реагировал. Отбор уроков в промпт шёл по
   одной частоте (`topLessons`: ORDER BY occurrences DESC), и получилось
   два вывернутых наизнанку следствия:

     1. ПЛОХОЙ УРОК ПОДНИМАЕТСЯ. Если формулировка не работает, дефект
        повторяется, счётчик РАСТЁТ — и правило поднимается в топ. То
        есть чем хуже урок, тем надёжнее он занимает место в промпте.
     2. ХОРОШИЙ УРОК ВЫТЕСНЯЕТСЯ. Сработавший урок останавливает дефект,
        частота перестаёт расти, правило уезжает вниз и выпадает из топа
        — после чего дефект возвращается. Успех выглядит как ненужность.

   Мест в промпте ровно `limit` (6): каждый бесполезный урок стоит одного
   полезного. Память, которая не умеет забывать, — не обучение, а склад.

   ЧТО ДЕЛАЕМ. Даём памяти три вещи, которых ей не хватало, чтобы
   пересматривать своё знание:

     revisions      INTEGER — сколько раз формулировку ПЕРЕПИСЫВАЛИ после
                              того, как она себя не оправдала. Предел
                              переписываний живёт в коде: правило, которое
                              не удалось сформулировать и со второй
                              попытки, обязано перестать жечь вызовы.
     retired_texts  TEXT    — JSON-массив формулировок, которые уже
                              доказали свою бесполезность. Без этой
                              колонки модель могла вернуть ровно тот же
                              текст, и мы приняли бы его как новый —
                              переписывание крутилось бы по кругу за
                              деньги. Это не «на будущее», а условие
                              работоспособности самого механизма.
     last_revised_at INTEGER — когда переписали (для витрины: «урок
                              переписан» без даты неотличим от «урок
                              такой и был»).

   ПОЧЕМУ ТОЧКА ОТСЧЁТА СБРАСЫВАЕТСЯ ИМЕННО ЗДЕСЬ. В волне 5
   `occurrences_at_authoring` фиксировался ОДИН раз и намеренно: повторная
   попытка разбора не должна была стирать измерение. Но переписывание —
   другое событие: новую формулировку нельзя судить по повторам, которые
   натворила старая. Поэтому при принятой ревизии точка отсчёта сдвигается
   на текущий счётчик, а прежний текст уходит в `retired_texts`. Два
   правила не противоречат друг другу: не сдвигаем на ПОПЫТКЕ, сдвигаем на
   СМЕНЕ текста.

   Ничего не удаляет и не переписывает: только добавляет колонки к
   `generation_lesson_texts`. Схема без 093 (таблицы ещё нет) — не ошибка:
   миграция 093 идёт раньше по номеру и создаёт таблицу; если её почему-то
   нет, эта миграция тихо ничего не делает, а платформа работает как до
   волны 6.

   Идемпотентно: состав колонок читается PRAGMA, повторный запуск —
   пустая операция. Самовызов на импорте (как 093).
   ================================================================ */

export function runLessonEffectivenessMigration() {
  /* Таблица могла не появиться (порядок импортов сломан, база старше 093).
     Падать здесь нельзя: миграции идут на boot, и падение унесёт весь сервер
     ради необязательного улучшения памяти. */
  const tableExists = db
    .prepare(`SELECT name FROM sqlite_master WHERE type = 'table' AND name = 'generation_lesson_texts'`)
    .get() as { name: string } | undefined

  if (!tableExists) {
    console.log("⏭️  Migration 097: generation_lesson_texts отсутствует — пропускаю (схема без 093)")
    return
  }

  const columns = new Set(
    (db.prepare(`PRAGMA table_info(generation_lesson_texts)`).all() as Array<{ name: string }>).map((c) => c.name),
  )

  /* DEFAULT обязателен: у существующих строк колонки заполнятся нулём, а не NULL,
     иначе арифметика «сколько раз переписывали» дала бы NULL вместо 0. */
  if (!columns.has("revisions")) {
    db.exec(`ALTER TABLE generation_lesson_texts ADD COLUMN revisions INTEGER NOT NULL DEFAULT 0`)
  }
  if (!columns.has("retired_texts")) {
    db.exec(`ALTER TABLE generation_lesson_texts ADD COLUMN retired_texts TEXT`)
  }
  if (!columns.has("last_revised_at")) {
    db.exec(`ALTER TABLE generation_lesson_texts ADD COLUMN last_revised_at INTEGER`)
  }

  console.log("✅ Migration 097: Lesson effectiveness ready (useless lessons can be rewritten and demoted)")
}

runLessonEffectivenessMigration()
