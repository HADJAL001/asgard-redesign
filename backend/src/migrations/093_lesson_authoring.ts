import db from "../lib/db"

/* ================================================================
   OSGARD · Миграция 093: платформа сама формулирует свои уроки
   ----------------------------------------------------------------
   ПРОБЛЕМА, КОТОРУЮ ЗАКРЫВАЕМ. С волны 2 платформа считает, на каких
   правилах ломается генерация (`generation_lessons`), а топ этих
   правил подмешивается в промпт следующей генерации. Но САМ ТЕКСТ
   урока — то единственное, что реально видит модель — живёт в
   рукописном словаре `LESSON_TEXT` внутри кода (lib/craft-corpus).
   Отсюда жёсткий предел обучения:

     `renderLessonsContract` фильтрует `.filter(l => LESSON_TEXT[l.rule])`

   Правило без рукописной формулировки копится в базе и молча
   выбрасывается из промпта. Волна 4 сделала это видимым (поле
   `silent` в сводке обучения), но не устранила: чтобы платформа
   научилась новому классу дефектов, ПРОГРАММИСТ должен заметить
   счётчик, придумать формулировку, написать код и задеплоить.

   Значит «платформа умнеет с каждой генерацией» было верно лишь
   наполовину: частоты уточнялись сами, а СОДЕРЖАНИЕ знания — нет.
   Новый, ранее не встречавшийся дефект платформа зафиксировать
   умеет, а сформулировать — нет.

   ЧТО ДЕЛАЕМ. Даём памяти ошибок место для текстов, которые платформа
   написала себе сама, разобрав РЕАЛЬНЫЙ дефект (lib/lesson-author):
   правило + сообщение сборки + фрагмент кода → формулировка урока.
   Рукописный словарь остаётся главным (человеческая формулировка
   надёжнее), эта таблица — второй эшелон для всего остального.

   Таблица `generation_lesson_texts` (rule → формулировка), поля:
     text         TEXT    — формулировка; NULL = попытка была, урок НЕ принят
                            валидацией. Важно хранить именно так: иначе
                            каждая следующая генерация заново жгла бы
                            вызов модели на том же безнадёжном правиле.
     source       TEXT    — кто автор ('ai'); задел на 'founder' вручную
     model        TEXT     — какая модель сформулировала (для отзыва партии)
     attempts     INTEGER — сколько раз пытались (предел попыток на правило)
     last_error   TEXT    — почему не приняли (видно в витрине /dev/memory)
     occurrences_at_authoring INTEGER — счётчик правила НА МОМЕНТ написания
                            урока. Разница с текущим = сколько раз дефект
                            повторился ПОСЛЕ того, как урок дошёл до модели.
                            Без этой колонки «обучение работает» — вера, а
                            не измерение.
     sample_message/sample_file — на каком дефекте учились (проверяемость:
                            основатель может убедиться, что урок не выдуман)
     diagnosis    TEXT    — объяснение модели, ПОЧЕМУ генератор так ошибается.
                            В промпт не уходит (там нужна короткая директива), но
                            без него урок нельзя оценить глазами: непонятно, разобрал
                            модель причину или угадала складную фразу.

   Ничего существующего не мутирует: `generation_lessons` не тронута,
   связь по `rule` без FK намеренно — уроки живут дольше счётчиков и
   не должны исчезать при чистке статистики.

   Идемпотентно: IF NOT EXISTS + PRAGMA-guard на колонки. Самовызов на
   импорте (как 092). Все обращения к БД в рантайме — ленивые, внутри
   функций (урок инцидента #59: модульный db.prepare на колонку новой
   миграции роняет boot).
   ================================================================ */

export function runLessonAuthoringMigration() {
  db.exec(`
    CREATE TABLE IF NOT EXISTS generation_lesson_texts (
      rule                     TEXT PRIMARY KEY,
      text                     TEXT,
      source                   TEXT NOT NULL DEFAULT 'ai',
      model                    TEXT,
      attempts                 INTEGER NOT NULL DEFAULT 0,
      last_error               TEXT,
      occurrences_at_authoring INTEGER NOT NULL DEFAULT 0,
      sample_message           TEXT,
      sample_file              TEXT,
      diagnosis                TEXT,
      created_at               INTEGER NOT NULL,
      updated_at               INTEGER NOT NULL
    );
  `)

  /* Витрина и промпт спрашивают «дай принятые уроки» — то есть выборка идёт по
     `text IS NOT NULL`. Индекс по source держит её дешёвой при росте таблицы. */
  db.exec(`CREATE INDEX IF NOT EXISTS idx_lesson_texts_source ON generation_lesson_texts(source)`)

  console.log("✅ Migration 093: Lesson authoring ready (platform can word its own lessons)")
}

runLessonAuthoringMigration()
