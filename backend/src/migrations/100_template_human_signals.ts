import db from "../lib/db"

/* ================================================================
   OSGARD · Миграция 100: человеческий сигнал у шаблона корпуса
   ----------------------------------------------------------------
   ПРОБЛЕМА, КОТОРУЮ ЗАКРЫВАЕМ. Качество шаблона (миграция 092)
   производно ТОЛЬКО от машины: вердикт сборки, балл интерфейса,
   число ремонтов. Машина отвечает на вопрос «скомпилировалось ли»,
   но не на вопрос «годится ли это человеку». А платформа уже знает
   ответ человека и молчит о нём:

     • `project_refinements` (миграция 089) — человек попросил
       переделать сгенерированное. Отрицательный сигнал, данные есть
       с первого дня механики доработок.
     • `projects.deploy_status='deployed'` / `live_url` (миграция 029)
       — человек выложил результат наружу под своим именем. Более
       сильного «годится» у платформы нет.

   Ни один из двух сигналов не доходил до отбора шаблонов, потому что
   ШАБЛОН НЕ СВЯЗАН С ПРОЕКТОМ-РОДИТЕЛЕМ: `project_templates` (030)
   хранит только выход генератора, и по строке шаблона невозможно
   узнать, чем кончилась та генерация у человека. Человеческий сигнал
   было буквально некуда применить.

   ЧТО ДЕЛАЕМ. Одна аддитивная колонка:
     source_project_id INTEGER — проект, из генерации которого шаблон
     сохранён. NULL допустим и означает ровно «сигнала нет».

   Приватность не страдает: связь — числовой id, содержимое шаблона
   по-прежнему только выход генератора (никаких user_id/промптов).
   Внешний ключ намеренно НЕ ставим: проект могут удалить, а шаблон
   после этого обязан жить дальше как обычный «без сигнала» — падать
   на удалении проекта корпус права не имеет.

   Grandfather: у старых шаблонов колонка NULL. Бэкфилл НЕВОЗМОЖЕН —
   связи никогда не существовало, а угадывать проект по имени
   означало бы придумать человеческий сигнал там, где его не было.
   Дельта у таких шаблонов = 0 (не штраф) — это отдельный негативный
   контроль в тестах: отсутствие сигнала не смеет работать как
   поголовный штраф.

   Идемпотентно: PRAGMA-guard. Самовызов на импорте.
   ================================================================ */

export function runTemplateHumanSignalsMigration() {
  const templatesExist = db
    .prepare(`SELECT name FROM sqlite_master WHERE type='table' AND name='project_templates'`)
    .get()

  if (!templatesExist) return

  const cols = (db.prepare(`PRAGMA table_info(project_templates)`).all() as Array<{ name: string }>).map((c) => c.name)

  if (!cols.includes("source_project_id")) {
    db.exec(`ALTER TABLE project_templates ADD COLUMN source_project_id INTEGER`)
    console.log("✅ Migration 100: added project_templates.source_project_id")
  }

  /* Отбор шаблона читает сигнал на каждой генерации темы — индекс по родителю
     держит чтение дешёвым и на выросшем корпусе. */
  db.exec(`CREATE INDEX IF NOT EXISTS idx_templates_source_project ON project_templates(source_project_id)`)

  console.log("✅ Migration 100: template human signals ready (deploy + refinements reach quality)")
}

runTemplateHumanSignalsMigration()
