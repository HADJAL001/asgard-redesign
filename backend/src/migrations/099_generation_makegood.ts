/* ================================================================
   OSGARD · Миграция 099: перегенерация за счёт платформы (make-good)
   ----------------------------------------------------------------
   Номер сдвинут с 098 на 099: 098 занят на origin/main другой веткой
   (098_lesson_teaching_baseline, инстансов работает несколько — см.
   asgard_multi_instance_protocol в памяти). Столкновение обнаружено
   не по ощущению, а проверкой origin/main и всех веток origin.
   ----------------------------------------------------------------
   Что было: если генерация выдавала НЕСОБИРАЕМОЕ приложение (инженерный
   вердикт `broken` или блокирующие ошибки импортов), человек всё равно
   платил — кредитами за платную глубину или дневной квотой за быструю.
   Платформа брала деньги за собственный промах и предлагала «попробовать
   снова» за тот же счёт. Это ровно та претензия, из-за которой рынок
   AI-сборщиков считают лотереей: неудачная попытка стоит как удачная.

   Здесь появляется право на ОДНУ перегенерацию за счёт платформы. Оно
   выдаётся автоматически в момент, когда платформа сама признала свой
   провал, и тратится на следующем запуске — без кредитов и без списания
   дневной квоты.

     • generation_makegoods — по строке на признанный промах:
       кому, за какой проект, какая глубина провалилась, во что она
       обошлась, причина, и когда право было использовано.

   Почему `project_id UNIQUE`: право привязано к ПРОВАЛУ, а не к попытке
   его исправить. Без уникальности повторный прогон ремонта того же
   проекта штамповал бы новые права — фарм бесплатных генераций на одном
   сломанном проекте.

   Почему отдельная таблица, а не колонка в `projects` или счётчик в
   `wallets`: право должно быть прослеживаемым (за что выдано, на что
   потрачено) — это компенсация, и она обязана иметь аудит. Мутировать
   общие таблицы ради этого не нужно.

   Grandfather: у прошлых сломанных генераций прав не появится — задним
   числом раздавать компенсации значило бы выдумать факты, которых никто
   не фиксировал (тот же принцип, что в 095 с расходом).

   Идемпотентно (CREATE ... IF NOT EXISTS). Самовызов на импорте (стиль
   089-097).
   ================================================================ */

export function runGenerationMakegoodMigration() {
  db.exec(`
    CREATE TABLE IF NOT EXISTS generation_makegoods (
      id                  INTEGER PRIMARY KEY AUTOINCREMENT,
      user_id             INTEGER NOT NULL,
      project_id          INTEGER NOT NULL UNIQUE,   -- один провал = одно право
      depth               TEXT NOT NULL,             -- глубина, которая провалилась
      credits             INTEGER NOT NULL DEFAULT 0,-- во что обошлась та попытка
      reason              TEXT NOT NULL,             -- broken | unbuildable | crashed
      created_at          INTEGER NOT NULL,
      consumed_at         INTEGER,                   -- NULL = право не использовано
      consumed_project_id INTEGER,                   -- на какую генерацию потрачено
      FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
      FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE
    );
  `)

  /* Горячий запрос — «есть ли у этого человека неиспользованное право»: он идёт
     на КАЖДОМ запуске генерации и в смете, поэтому индекс по (user_id, consumed_at). */
  db.exec(
    `CREATE INDEX IF NOT EXISTS idx_makegood_user_open ON generation_makegoods(user_id, consumed_at, id);`,
  )

  console.log("✅ Migration 099: Generation make-good ready (прошлые провалы не компенсируются задним числом)")
}

runGenerationMakegoodMigration()
