/* ================================================================
   OSGARD · test helper — форс in-memory SQLite для in-process тестов
   ----------------------------------------------------------------
   lib/db читает process.env.DB_PATH ОДИН РАЗ на импорте и по умолчанию
   открывает рабочий файл ./data/osgard.db с PRAGMA foreign_keys=ON.
   Тест, который импортирует lib/db напрямую (не через spawn отдельного
   сервера с собственным DB_PATH), обязан переключить путь на :memory:
   ЕЩЁ ДО того, как lib/db выполнит `new Database(dbPath)`.

   ES-импорты хойстятся, поэтому inline-присвоение env внутри тест-файла
   отрабатывает уже ПОСЛЕ require("../lib/db"). Решение — вынести side-
   effect в отдельный модуль и импортировать его ПЕРВОЙ строкой теста:
   импорты исполняются в порядке следования, значит этот сработает раньше
   загрузки lib/db.

   Раньше файл полагался на то, что DB_PATH=:memory: задаст ВЫЗЫВАЮЩАЯ
   команда. Под общим `npm test` (tsx --test glob) переменная не
   передавалась → тест бил по боевой dev-БД: часть кейсов падала на
   SQLITE_CONSTRAINT_FOREIGNKEY (idempotency_keys.user_id → users), а сами
   прогоны засоряли ./data/osgard.db. Здесь фиксируем :memory: независимо
   от способа запуска — но не перетираем явно заданный извне путь.
   ================================================================ */

if (!process.env.DB_PATH) {
  process.env.DB_PATH = ":memory:"
}
