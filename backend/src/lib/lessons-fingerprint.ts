import { createHash } from "node:crypto"

/* ================================================================
   OSGARD · Отпечаток набора уроков (волна 7)
   ----------------------------------------------------------------
   Две чистые функции над готовым блоком «выученные уроки»
   (lib/craft-corpus.renderLessonsContract). Вынесены в отдельный
   модуль намеренно: их импортирует сервис генерации ради ключа кэша, а
   `craft-corpus` открывает соединение с БД на импорте — тянуть базу в
   генератор ради хэша строки незачем.

   Функции чистые и от БД не зависят, поэтому их можно проверять
   напрямую, без миграций и без сети.
   ================================================================ */

/**
 * Отпечаток набора уроков — короткий хэш ТОГО ЖЕ текста, который уходит в промпт.
 *
 * Считается от готовой строки контракта, а не от списка правил, и это принципиально:
 * отпечаток обязан меняться при ЛЮБОМ изменении, которое видит модель, — включая
 * переписанную формулировку того же правила (волна 6) и смену порядка отбора. Хэш от
 * имён правил такое изменение пропустил бы, и кэш продолжал бы отдавать код, рождённый
 * под прежним знанием, целые сутки.
 *
 * Пустая память даёт `"none"`, а не пустую строку: ключ кэша печатается в логи и обязан
 * читаться глазами.
 */
export function lessonsFingerprint(contract: string): string {
  const text = contract.trim()
  if (!text) return "none"
  return createHash("sha256").update(text).digest("hex").slice(0, 16)
}

/**
 * Сколько уроков реально стоит в контракте — то есть сколько их дошло до модели.
 *
 * Считается по нумерованным строкам самого блока, а не по `selectPromptLessons`:
 * измерять надо доставленное, а не задуманное. Если блок собрался пустым или урок
 * потерялся по дороге, цифра обязана это показать.
 */
export function countLessonsInContract(contract: string): number {
  if (!contract.trim()) return 0
  return contract.split("\n").filter((line) => /^\d+\.\s/.test(line)).length
}
