/** Почему заявка непонятна. Код уезжает на фронт — там свой текст вопроса. */
export type UnclearReason =
  /** Символы замены U+FFFD: текст уже потерян до нас, читать нечего. */
  | "replacement-chars"
  /** Классическая двойная перекодировка UTF-8↔Latin-1/CP1251 («ÐžÐ´Ð½Ð¾…»). */
  | "mojibake"
  /** Ни одного слова: только знаки, цифры, эмодзи («!!! 123 ???»). */
  | "no-words"

export type ClarityVerdict =
  | { clear: true }
  | {
      clear: false
      reason: UnclearReason
      /** Человеческий вопрос — его увидит автор заявки. */
      question: string
      /** Что платформа прочитала: показываем, а не прячем за «ошибкой». */
      sample: string
    }

/** Сколько символов заявки вообще разбираем — как PARSE_WINDOW в project-title. */
const PARSE_WINDOW = 400

/** Показать человеку кусок того, что реально дошло до сервера. */
const SAMPLE_LENGTH = 80

/* Латиница-«обломки» UTF-8, прочитанного как однобайтовая кодировка. Кириллица
   в UTF-8 — это байты 0xD0/0xD1 + второй байт, поэтому испорченный текст
   кишит Ð/Ñ, а также Ã/Â/â€ от других пар. В нормальном европейском тексте
   эти буквы встречаются (é, ü, ñ), но не в каждом втором символе. */
const MOJIBAKE_CHARS = /[À-ÿŒ-Ÿˆ–—‘-„…‰‹›€™]/g
/** Заглавные Ð Ñ Ã Â и связка â€ — то, во что превращаются старшие байты UTF-8. */
const MOJIBAKE_MARKERS = /[ÐÑÃÂ]|â€/

/** Буква любого алфавита — латиница, кириллица, казахские/греческие и прочие. */
const LETTER = /\p{L}/u

const QUESTIONS: Record<UnclearReason, string> = {
  "replacement-chars":
    "Текст заявки дошёл до нас повреждённым — часть символов потеряна ещё при передаче. Напишите идею ещё раз, пожалуйста: что за приложение и для кого.",
  mojibake:
    "Текст заявки дошёл в поломанной кодировке — прочитать идею невозможно. Напишите её ещё раз, пожалуйста: что за приложение и для кого.",
  "no-words":
    "В заявке нет ни одного слова — из знаков и цифр нельзя понять, какое приложение делать. Опишите идею одной фразой: что за приложение и для кого.",
}

function sampleOf(text: string): string {
  const flat = text.replace(/\s+/g, " ").trim()
  return flat.length > SAMPLE_LENGTH ? `${flat.slice(0, SAMPLE_LENGTH)}…` : flat
}

/**
 * Понятна ли заявка настолько, чтобы вообще начинать генерацию.
 *
 * На вход — то же, что уходит в генератор: название и/или описание идеи.
 * Пустой ввод сюда не доходит (его отсекает роут раньше и другим текстом),
 * но и на нём вердикт честный: пустая строка — это «нет слов».
 */
export function assessRequestClarity(input: { name?: string | null; hint?: string | null }): ClarityVerdict {
  const raw = [input.name, input.hint]
    .map((v) => (typeof v === "string" ? v : ""))
    .join(" ")
    .slice(0, PARSE_WINDOW)

  const text = raw.trim()
  if (!text) {
    return { clear: false, reason: "no-words", question: QUESTIONS["no-words"], sample: "" }
  }

  /* 1. Символы замены. Один такой символ — случайность (человек мог вставить
        значок), но заметная доля означает, что текст испорчен до нас. */
  const replacements = (text.match(/�/g) || []).length
  if (replacements >= 3 || replacements / text.length > 0.05) {
    return {
      clear: false,
      reason: "replacement-chars",
      question: QUESTIONS["replacement-chars"],
      sample: sampleOf(text),
    }
  }

  /* 2. Двойная перекодировка. Требуем ОБА признака сразу — характерную пару
        символов и высокую их плотность. По отдельности каждый признак врёт:
        «Ñandú» — живое слово, а редкая Ã встречается в любом французском
        тексте. Порог 20% от букв: столько «обломков» в осмысленном тексте
        человеческого языка не бывает. */
  const letters = [...text].filter((ch) => LETTER.test(ch)).length
  const mojibakeChars = (text.match(MOJIBAKE_CHARS) || []).length
  if (letters > 0 && MOJIBAKE_MARKERS.test(text) && mojibakeChars / letters > 0.2) {
    return { clear: false, reason: "mojibake", question: QUESTIONS.mojibake, sample: sampleOf(text) }
  }

  /* 3. Слов нет вовсе. «Слово» — две буквы подряд: этого хватает и для
        «ИИ», и для «CRM», и для казахского «үй». Одиночная буква словом не
        считается, иначе «а!!!» пройдёт как заявка. */
  if (!/\p{L}{2}/u.test(text)) {
    return { clear: false, reason: "no-words", question: QUESTIONS["no-words"], sample: sampleOf(text) }
  }

  return { clear: true }
}
