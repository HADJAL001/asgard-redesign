/* ================================================================
   OSGARD · Профиль сгенерированного приложения
   ----------------------------------------------------------------
   До сих пор генератор умел ровно одно приложение — статический
   экспорт (`output: "export"`): только клиент и localStorage. Это
   зашито в трёх независимых местах — шаблон каркаса, промпты и
   правила целостности, — и каждое из них считало серверный код
   дефектом БЕЗУСЛОВНО. Живая прод-генерация показала цену: в 48
   файлах готового приложения не было ни одного API-роута и ни
   одного обращения к базе, то есть платформа делала витрину, а не
   продукт.

   Профиль снимает это ограничение не «выключением проверок», а
   явным контрактом: каждое приложение знает, в каком режиме оно
   собирается, и правила применяются по режиму.

     static    — как раньше: только клиент, статический экспорт,
                 деплой на статический хостинг (Netlify).
     fullstack — API-роуты, серверные компоненты, доступ к своей
                 базе Supabase. Собирается обычным `next build`.

   Здесь же живёт список пакетов, разрешённых профилю. Он объявлен
   ОДИН РАЗ по той же причине, по которой набор каркаса переехал в
   app-scaffold-deps: две рукописные копии одного списка уже
   расходились молча, и «кэш сборок» существовал только на бумаге.
   package.json приложения и allow-list проверки целостности обязаны
   читать один источник.
   ================================================================ */

export type AppProfile = "static" | "fullstack"

export const DEFAULT_APP_PROFILE: AppProfile = "static"

/** Приводит значение из БД/запроса к профилю. Неизвестное — самый безопасный режим. */
export function normalizeAppProfile(value: unknown): AppProfile {
  return value === "fullstack" ? "fullstack" : DEFAULT_APP_PROFILE
}

/**
 * Пакеты, доступные fullstack-приложению сверх набора каркаса. Список намеренно
 * узкий: `dependency-missing` — содержательная проверка, и чем шире allow-list,
 * тем меньше она значит. Доступ к базе — только через официальный клиент
 * Supabase; свои драйверы Postgres в сгенерированном коде запрещены (креды в
 * браузерном бандле — прямая утечка базы).
 */
export const FULLSTACK_DEPENDENCIES: Readonly<Record<string, string>> = {
  "@supabase/supabase-js": "^2.45.0",
  "@supabase/ssr": "^0.5.0",
}

/** Разрешён ли профилю серверный код (API-роуты, Server Actions, next/headers). */
export function allowsServerCode(profile: AppProfile): boolean {
  return profile === "fullstack"
}
