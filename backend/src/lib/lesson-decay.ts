/* ================================================================
   OSGARD · Давление дефекта: частота на генерацию и затухание (волна 7, п.2→3)
   ----------------------------------------------------------------
   ЗАЧЕМ ЭТОТ МОДУЛЬ СУЩЕСТВУЕТ. Отбор уроков в промпт шёл по абсолютному
   счётчику повторов (`ORDER BY occurrences DESC`). У абсолютного счётчика
   два свойства, и оба работают против платформы:

   1. ОН НИКОГДА НЕ УМЕНЬШАЕТСЯ. Дефект, который генератор допускал сто
      генераций назад и с тех пор ни разу — навсегда остаётся в топе с
      своими пятьюдесятью повторами. Мест в промпте шесть. Новый класс
      дефекта, ломающий код прямо сейчас, в промпт не пробьётся: топ
      заморожен историей. `last_seen` для этого и писался с волны 2 — и
      ни разу не читался при выборе.

   2. У НЕГО НЕТ ЗНАМЕНАТЕЛЯ. «Дефект повторился дважды после обучения» —
      это провал урока при четырёх генерациях и блестящий успех при
      тысяче. При растущем трафике улучшение неотличимо от деградации,
      а вердикт «формулировка не работает» выносился по абсолютному
      числу, то есть по объёму трафика.

   ЧТО ЗДЕСЬ СДЕЛАНО. Две чистые функции без обращений к БД: частота на
   генерацию (`repeatRate`) и давление дефекта с затуханием
   (`lessonPressure`). Обе — арифметика, поэтому их можно проверить
   тестом без базы и прочитать глазами.

   ПОЧЕМУ ЗАТУХАНИЕ МЕРЯЕТСЯ В ГЕНЕРАЦИЯХ, А НЕ В ДНЯХ. Это главное
   решение модуля. Платформа, простоявшая месяц без генераций, не
   получила ни одного нового факта — ни за урок, ни против него. Забыть
   за это время выученное значило бы наказать память за календарь:
   после отпуска платформа выкатила бы людям код, из которого вычистили
   уроки, ничего при этом не измерив. Возраст дефекта считается числом
   генераций, случившихся с последней встречи, — то есть числом
   ВОЗМОЖНОСТЕЙ повториться, которыми дефект не воспользовался.

   ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО. Ни удаления уроков (`DELETE`), ни обнуления
   счётчиков. Затухание меняет только ОЧЕРЕДЬ на место в промпте, а
   факты в базе остаются как были: дефект, вернувшийся через год, обязан
   поднять правило обратно одним повтором, а не начинать с нуля.
   ================================================================ */

/**
 * Через сколько генераций давление дефекта падает вдвое.
 *
 * Сорок — не круглое число ради красоты: одна генерация ничего не значит (дефект мог
 * не встретиться по несвязанным причинам — другая тема, меньше файлов), а сотни
 * означали бы, что затухание не работает вовсе. Сорок генераций — это порядок
 * величины «платформа заметно изменилась»: правило, не встретившееся за столько
 * попыток, скорее исправлено, чем случайно пропущено.
 */
export const PRESSURE_HALF_LIFE_GENERATIONS = 40

/**
 * Ниже этого множителя затухание не опускается.
 *
 * Без пола давление старого правила уходит в машинный ноль, и правило становится
 * НЕОТЛИЧИМЫМ от правила без повторов вообще — сортировка теряет остаток знания и
 * начинает решать по вторичному ключу (имени правила). Пол оставляет истории вес,
 * которого хватает, чтобы старое частое правило стояло выше старого редкого.
 */
export const PRESSURE_DECAY_FLOOR = 0.02

/**
 * Доля генераций, в которых дефект возвращается после обучения, чтобы формулировку
 * считать провалившейся.
 *
 * Пятая часть — порог, при котором урок явно не работает: каждая пятая генерация
 * наступает на те же грабли, хотя модель предупреждена. Это ЧАСТОТА, а не счётчик:
 * при тысяче генераций два повтора больше не приговор, а при пяти — приговор.
 */
export const REPEAT_FAIL_RATE = 0.2

/**
 * Сколько генераций должно пройти после начала обучения, чтобы судить о частоте.
 *
 * Без зрелости первая же генерация с повтором давала бы частоту 100% и мгновенный
 * приговор формулировке, которую модель видела один раз. Пять — минимум, при котором
 * частота 20% (порог провала) вообще выразима: один повтор из пяти.
 */
export const RATE_VERDICT_MIN_GENERATIONS = 5

/**
 * Множитель затухания по числу генераций, прошедших с последней встречи дефекта.
 *
 * Экспонента, а не линейка: линейное затухание с любым наклоном либо обнуляет знание
 * на конечном горизонте (после N генераций правило исчезает совсем), либо не затухает
 * заметно вовсе. Экспонента убывает всегда и никогда не достигает нуля — ровно то
 * свойство, которое здесь нужно.
 *
 * `null` на входе — «журнала генераций нет» (схема без 094 или пустой журнал). Тогда
 * множитель равен единице: затухание требует знаменателя, и выдумывать его нельзя.
 * Без журнала отбор обязан работать ровно как до этой волны.
 */
export function decayFactor(generationsSinceLastSeen: number | null): number {
  if (generationsSinceLastSeen === null || generationsSinceLastSeen === undefined) return 1
  const age = Math.max(0, generationsSinceLastSeen)
  const raw = Math.pow(0.5, age / PRESSURE_HALF_LIFE_GENERATIONS)
  return Math.max(PRESSURE_DECAY_FLOOR, raw)
}

/**
 * Давление дефекта — то, чем правила соревнуются за место в промпте.
 *
 * Это НЕ «сколько раз ломалось всего», а «насколько дефект актуален»: повторы,
 * взвешенные свежестью. Пятьдесят повторов, последний из которых был двести генераций
 * назад, дают меньшее давление, чем четыре повтора на этой неделе, — и это правильный
 * порядок: промпт должен предупреждать о том, что ломается, а не о том, что ломалось.
 */
export function lessonPressure(count: number, generationsSinceLastSeen: number | null): number {
  const occurrences = Math.max(0, count)
  return occurrences * decayFactor(generationsSinceLastSeen)
}

/**
 * Частота возврата дефекта на генерацию: сколько повторов пришлось на одну генерацию,
 * случившуюся после начала обучения.
 *
 * `null` — знаменателя нет (журнала генераций нет, либо после начала обучения не
 * случилось ни одной генерации). Это не ноль: «дефект не возвращался» и «мерить нечем»
 * обязаны различаться, иначе урок, о котором ничего не известно, был бы объявлен
 * работающим.
 *
 * Значение ограничено единицей сверху. Причина честная и её надо знать: повторы
 * копятся во ВСЕХ генерациях, а не только в тех, где урок реально был в промпте
 * (журнал хранит число уроков и отпечаток набора, но не список правил). Поэтому
 * частота — верхняя оценка вины формулировки, и превысить «каждую генерацию» она не
 * имеет права.
 */
export function repeatRate(repeatedAfterLearning: number | null, generationsSinceTeaching: number | null): number | null {
  if (repeatedAfterLearning === null || repeatedAfterLearning === undefined) return null
  if (generationsSinceTeaching === null || generationsSinceTeaching === undefined) return null
  if (generationsSinceTeaching <= 0) return null
  const rate = Math.max(0, repeatedAfterLearning) / generationsSinceTeaching
  return Math.min(1, Math.round(rate * 1000) / 1000)
}
