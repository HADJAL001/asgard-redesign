/* ================================================================
   OSGARD · Название проекта из описания идеи
   ----------------------------------------------------------------
   Зачем: «первый клик создаёт проект». Человек описывает приложение
   («сделай мне сайт кофейни с меню и бронированием столика») и вправе
   ждать проект, а не анкету с обязательным полем «Название». Имя
   выводится ЗДЕСЬ — детерминированным кодом.

   Почему не AI: имя нужно синхронно, в том же запросе, до ответа 202.
   Вызов модели добавил бы секунды, стоимость и ещё одну точку отказа
   на самом узком месте продукта. Заголовок — задача разбора текста, а
   не рассуждения.

   Свойства, на которые опирается остальной код:
   • детерминированность — один вход даёт один выход всегда;
   • идемпотентность — deriveProjectTitle(deriveProjectTitle(x)) даёт
     то же самое, поэтому безопасно вызывать повторно на уже выведенном
     имени (роут выводит его для леджера, createGeneratedProject — для
     страховки на входах, которые роут не проходят);
   • никогда не бросает и никогда не возвращает пустую строку: на мусоре
     отдаёт FALLBACK_TITLE, чтобы генерация не падала из-за заголовка.
   ================================================================ */

/** Имя, когда из текста нечего взять (пустой ввод, только смайлики, только служебные слова). */
export const FALLBACK_TITLE = "Новый проект"

/** Предел длины имени. Держим коротким: имя живёт на карточке проекта, в
 *  строке транзакции и в названиях стартовых артефактов — длинная фраза
 *  ломает вид во всех трёх местах. */
export const MAX_TITLE_LENGTH = 48

/** Сколько символов описания вообще смотрим. Имя берётся из первой фразы —
 *  дальше в тексте его нет, а разбор чужого текста произвольной длины лучше
 *  ограничить явно. */
const PARSE_WINDOW = 400

/* Обращения к платформе в начале фразы: они про ЗАПРОС, а не про проект.
   Снимаем циклом, потому что их бывает несколько подряд («сделай мне
   пожалуйста приложение…» → «приложение…»). Односложные «мне»/«нам» стоят
   после глаголов намеренно: сами по себе они начало осмысленной фразы. */
const LEAD_INS: RegExp[] = [
  /^(?:пожалуйста|плиз)[\s,]+/i,
  /^(?:а\s+)?(?:можешь|можно|хочу|хочется|хотелось\s+бы|нужно|нужен|нужна|нужны|надо|давай|давайте)\s+/i,
  /* «мне»/«нам» сразу после глагола — часть просьбы («сделай мне сайт»). */
  /^(?:сделай|создай|сгенерируй|сгенерировать|построй|собери|напиши|разработай|сделать|создать|построить|собрать|написать|разработать)(?:\s+(?:мне|нам))?\s+/i,
  /* «Мне»/«нам» в начале снимаем ТОЛЬКО перед просьбой: «мне нужен трекер» →
     «трекер», а «мне нравится кофе» начала не теряет — там это часть мысли.
     Слова в просмотре вперёд — префиксы всех форм («нуж» покрывает и «нужен»,
     и «нужна»); полная форма промахнулась бы на другом окончании. */
  /^(?:мне|нам)(?:\s+бы)?\s+(?=(?:нуж|надо|хочет|хотелось|сдела|созда|сгенериру|собер|собра|напис|постро|разработ))/i,
  /^(?:please|plz)[\s,]+/i,
  /^(?:can\s+you|could\s+you|i\s+want|i\s+need|i'd\s+like|we\s+need|let's)\s+/i,
  /^(?:make|create|build|generate|write|develop|design)\s+(?:me\s+)?/i,
  /* Артикль в начале — остаток англоязычной просьбы («I want a landing page»),
     в заголовке он лишний. В русском аналога нет, поэтому правило безопасно. */
  /^(?:a|an|the)\s+(?=\p{L})/iu,
]

/* Хвост, повисший после обрезки по слову: предлог или союз в конце имени
   читается как обрыв на середине мысли. Убираем. */
const DANGLING_TAIL =
  /\s+(?:и|или|а|но|с|со|в|во|на|по|для|из|от|до|к|ко|о|об|при|про|у|за|над|под|где|что|чтобы|как|the|a|an|and|or|with|for|of|to|in|on|at|by|from)$/i

/** Незначащие символы: управляющие (\p{Cc}) и форматирующие (\p{Cf}).
 *  Приходят из вставки и распознавания речи, делают длину строки обманчивой. */
const INVISIBLE_CHARS = /[\p{Cc}\p{Cf}]/gu

/** Есть ли в строке хоть одна буква или цифра (иначе заголовок бессмысленный). */
function hasMeaning(value: string): boolean {
  return /[\p{L}\p{N}]/u.test(value)
}

/** Первая буква — заглавная, но только если человек не задал регистр сам.
 *  «iOS-трекер сна» должен остаться собой, а не стать «IOS-трекером»:
 *  заглавная внутри первого слова — признак осознанного написания. */
function capitalizeFirst(value: string): string {
  const firstWord = value.split(/\s/, 1)[0] ?? ""
  if (/\p{Lu}/u.test(firstWord)) return value

  const match = /[\p{L}\p{N}]/u.exec(value)
  if (!match || match.index === undefined) return value
  const i = match.index
  return value.slice(0, i) + value.charAt(i).toLocaleUpperCase("ru-RU") + value.slice(i + 1)
}

/** Снимает обёртки, которыми люди и распознавание речи украшают текст:
 *  кавычки, звёздочки Markdown, маркеры списка, номер пункта. */
function unwrap(value: string): string {
  return value
    .replace(/^[\s>*_#-]+/, "")
    .replace(/^\d+[.)]\s+/, "")
    .replace(/^[«"'“„`]+/, "")
    .replace(/[»"'”“`*_]+$/, "")
    .trim()
}

/** Убирает повисший хвост-предлог столько раз, сколько нужно («…для» → «…»). */
function trimDanglingTail(value: string): string {
  let out = value
  for (let i = 0; i < 4; i++) {
    const next = out.replace(DANGLING_TAIL, "")
    if (next === out) break
    out = next
  }
  return out
}

/**
 * Выводит короткое человеческое название проекта из свободного описания.
 *
 * Шаги: нормализация → снятие обращений к платформе → первая фраза →
 * обрезка по слову до MAX_TITLE_LENGTH → чистка хвоста → заглавная буква.
 *
 * Всегда возвращает непустую строку (в крайнем случае FALLBACK_TITLE).
 */
export function deriveProjectTitle(idea: string | null | undefined): string {
  if (typeof idea !== "string") return FALLBACK_TITLE

  /* Перевод строки — такая же граница мысли, как точка (голосовой ввод и
     вставка из заметок дают именно его). Заменяем ПЕРВЫМ делом: сам он тоже
     управляющий символ, и чистка невидимых стёрла бы границу в пробел. */
  /* Разбираем только начало текста: имя всё равно берётся из первой фразы, а
     длина `hint` сверху не ограничена — регулярные правила не должны работать
     по описанию произвольного размера. */
  let text = idea.slice(0, PARSE_WINDOW).replace(/[\r\n]+/g, ". ")
  text = text.replace(INVISIBLE_CHARS, " ")
  text = text.replace(/\s+/g, " ").trim()
  if (!text) return FALLBACK_TITLE

  text = unwrap(text)

  for (let i = 0; i < LEAD_INS.length * 2; i++) {
    const before = text
    for (const lead of LEAD_INS) {
      text = text.replace(lead, "")
    }
    text = unwrap(text)
    /* Предел итераций — страховка от правила, которое совпало, но ничего не
       отрезало: без него цикл был бы бесконечным. */
    if (text === before) break
  }

  /* Первая фраза = суть. Остальное («…и чтобы ещё была тёмная тема») уходит
     в бриф генерации, но не в заголовок. */
  const sentenceEnd = text.search(/[.!?;·•]/)
  if (sentenceEnd > 0) text = text.slice(0, sentenceEnd)
  text = text.replace(/[\s,;:—–-]+$/, "").trim()

  if (!hasMeaning(text)) return FALLBACK_TITLE

  if (text.length > MAX_TITLE_LENGTH) {
    /* Режем по границе слова. Если первое же слово длиннее предела (ссылка,
       слипшийся текст) — режем жёстко: пустое имя хуже обрезанного. */
    const head = text.slice(0, MAX_TITLE_LENGTH + 1)
    const lastSpace = head.lastIndexOf(" ")
    text = lastSpace > 0 ? head.slice(0, lastSpace) : text.slice(0, MAX_TITLE_LENGTH)
    text = trimDanglingTail(text.replace(/[\s,;:—–-]+$/, ""))
  }

  text = text.trim()
  if (!hasMeaning(text)) return FALLBACK_TITLE

  return capitalizeFirst(text)
}

/**
 * Название проекта для генерации: явное имя пользователя важнее выведенного.
 * Единая точка для всех входов генерации (веб, студия, B2B API) — чтобы
 * проект, созданный из одного и того же текста, назывался одинаково везде.
 */
export function resolveProjectTitle(name?: string | null, idea?: string | null): string {
  const explicit = typeof name === "string" ? name.trim() : ""
  if (explicit) return explicit
  return deriveProjectTitle(idea)
}
