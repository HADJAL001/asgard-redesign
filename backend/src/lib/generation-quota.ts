/* ================================================================
   OSGARD · Лимиты по тарифу: разбор значения из тарифной таблицы
   ----------------------------------------------------------------
   Здесь живёт одна маленькая функция, из-за отсутствия которой платформа
   годами обслуживала платящих людей по бесплатной квоте.

   ДЕФЕКТ, КОТОРЫЙ ЭТОТ МОДУЛЬ ЗАКРЫВАЕТ. По всем квотам был повторён
   один и тот же приём:

       LIMITS[plan] ?? LIMITS.free

   В этих таблицах `null` означает «без ограничений» — а `??` считает
   null отсутствием значения и подставляет лимит бесплатного тарифа.
   То есть каждый тариф, которому безлимит и был обещан, молча получал
   квоту free. Нашлось живой проверкой сметы: аккаунт верхнего тарифа
   получил «дневной лимит быстрых генераций (5) исчерпан».

   Вторая половина той же ошибки — устаревший словарь тарифов. Миграция
   050 переименовала ключи (architect→pro, master→supreme, legend→elite),
   но таблица лимитов генераций проектов осталась на старых именах: ни
   один реальный тариф в неё уже не попадал, и все они сваливались в
   free по тому же `??`.

   Отсюда два правила, которые модуль удерживает:
     1. Известный тариф со значением null — безлимит, а не квота free.
     2. Незнакомый тариф — осторожно как free: про него не известно
        ничего, и щедрость к неизвестности стоила бы денег.
   ================================================================ */

/**
 * Лимит тарифа из тарифной таблицы: `null` — без ограничений, число — предел.
 *
 * `hasOwnProperty`, а не `plan in map` и не `??`: `in` пропускал бы имена из
 * прототипа Object (plan="constructor" вернул бы функцию вместо числа), а `??`
 * ломал бы безлимит.
 */
export function planLimit<T extends number | null>(limits: Record<string, T>, plan: string): T {
  return Object.prototype.hasOwnProperty.call(limits, plan) ? limits[plan] : limits.free
}

/**
 * Дневной лимит БЕСПЛАТНЫХ (quick) генераций проектов по тарифу. null = без лимита.
 * Платные глубины списывают кредиты и в эту квоту не входят.
 *
 * Ключи — действующий словарь тарифов (миграция 050). Прежние имена оставлены
 * псевдонимами: базы, не прошедшие 050, ещё держат их в users.plan, и молча
 * ронять такие аккаунты в free — тот же дефект, только с другой стороны.
 *
 * `duo` в старой таблице не существовал; он выше supreme и в порядке тарифов
 * (lib/stripe PLAN_ORDER), и по комиссии рынка (lib/market-fees), поэтому получает
 * не меньше supreme. Ровно supreme, а не безлимит: расширять обещание тарифа —
 * решение продуктовое, а не техническое.
 */
export const PROJECT_GENERATION_DAILY_LIMITS: Record<string, number | null> = {
  free: 5,
  pro: 15,
  supreme: 40,
  duo: 40,
  elite: null,

  /* Легаси-имена до миграции 050 — те же уровни. */
  architect: 15,
  master: 40,
  legend: null,
}

/** Дневной лимит быстрых генераций для тарифа. null — без ограничений. */
export function resolveDailyLimit(plan: string): number | null {
  return planLimit(PROJECT_GENERATION_DAILY_LIMITS, plan)
}

/** Остаток попыток на сегодня. null — без ограничений (это не то же, что 0). */
export function quotaRemaining(dailyLimit: number | null, usedToday: number): number | null {
  return dailyLimit === null ? null : Math.max(0, dailyLimit - usedToday)
}
