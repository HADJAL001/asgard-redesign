"use client"

/* ================================================================
   AmbientBackdrop — глобальный ЖИВОЙ фон всей платформы.
   ----------------------------------------------------------------
   Проблема, которую решает: раньше атмосфера (CosmicBackdrop) была
   заперта внутри дашборда и вдобавок статична — остальные страницы
   (Кузница/Маркет/…) выглядели «мёртвыми». Этот слой монтируется один
   раз в AppShell и дышит на КАЖДОЙ странице.

   Дисциплина:
   • Производительность — анимируем только transform/opacity (композит на
     GPU, без layout/paint), без JS-цикла и ре-рендеров. Слой чисто
     презентационный: pointer-events:none, aria-hidden, z-0 (под контентом).
   • Доступность — при prefers-reduced-motion всё замирает (см. globals.css),
     фон становится статичной глубиной без движения.
   • Домен — это атмосфера/первое впечатление (конверсия), не бизнес-логика
     генерации: файлы форджа/маркета B не трогаются, слой рисуется ПОД ними.
   ================================================================ */

export function AmbientBackdrop() {
  return (
    <div className="ambient-backdrop" aria-hidden="true">
      {/* Обсидиановая база глубины — тот же язык, что у дашборда (#040407→navy). */}
      <div className="ambient-base" />

      {/* Три медленно дрейфующих аврора-пятна: бирюза / королевский синий / золото.
          Разные скорости и траектории → «параллакс живого мира», не зацикленность. */}
      <div className="ambient-aurora ambient-aurora--teal" />
      <div className="ambient-aurora ambient-aurora--royal" />
      <div className="ambient-aurora ambient-aurora--gold" />

      {/* Мерцающий звёздный слой (дышит прозрачностью поверх статичных body-звёзд). */}
      <div className="ambient-stars" />

      {/* Виньетка — фокус к центру, премиальная «оправа». */}
      <div className="ambient-vignette" />
    </div>
  )
}
